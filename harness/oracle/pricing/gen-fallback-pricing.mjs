import { LEGACY_FALLBACK_PRICING } from '@/lib/llm/fallback-data';

const PROVIDERS = [
  'ANTHROPIC',
  'OPENAI',
  'GOOGLE',
  'GROK',
  'OPENROUTER',
  'OLLAMA',
  'OPENAI_COMPATIBLE',
];

function num(n) {
  // Emit a Rust f64 literal. Ensure a decimal point so it types as f64.
  if (!Number.isFinite(n)) throw new Error(`non-finite cost: ${n}`);
  const s = String(n);
  return s.includes('.') || s.includes('e') || s.includes('E') ? s : `${s}.0`;
}
function optCtx(v) {
  return v === null || v === undefined ? 'None' : `Some(${v})`;
}
function optBool(v) {
  return v === undefined ? 'None' : `Some(${v ? 'true' : 'false'})`;
}
function rustStr(s) {
  // Rust string literal via JSON escaping (the fields here are plain ASCII).
  return JSON.stringify(s);
}

