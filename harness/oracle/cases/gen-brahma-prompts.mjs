/**
 * Mechanical extractor for the Brahma Console system-prompt surface (W4.5b).
 * Emits the byte-exact `services/brahma_console/prompt_text.rs` submodule (the
 * generated `prompt_text` precedent: `memory_tasks/prompt_text.rs`, the image
 * scene tasks, the danger gatekeeper).
 *
 * Two constants:
 *   - `BRAHMA_BASE_BRIEF` — the base neutral-assistant brief, recovered by driving
 *     v4's REAL `buildBrahmaSystemPrompt` with `includeSqlAccess:false` and no tool
 *     instructions (parts = [baseBrief], joined + trimmed = the base brief itself).
 *   - `BRAHMA_SQL_PROMPT` — v4's exported constant verbatim.
 *
 * Both bodies hold literal backticks (`run_sql` etc.) which raw Rust strings carry
 * verbatim; the fence picker avoids any `"#` collision.
 *
 * Run under tsx from the v4 checkout so the `@/` aliases resolve:
 *   N=~/.nvm/versions/node/v24.13.1/bin ; V5=~/source/quilltap-v5
 *   cd ~/source/quilltap-server
 *   $N/npx tsx $V5/harness/oracle/cases/gen-brahma-prompts.mjs \
 *     $V5/crates/quilltap-core/src/services/brahma_console/prompt_text.rs
 */
import * as fs from 'node:fs';

const OUT = process.argv[2];
if (!OUT) {
  console.error('usage: tsx gen-brahma-prompts.mjs <out.rs>');
  process.exit(1);
}

const { buildBrahmaSystemPrompt } = await import('@/lib/brahma-console/system-prompt-builder');
const { BRAHMA_SQL_PROMPT } = await import('@/lib/brahma-console/brahma-sql-prompt');

// The base brief in isolation: no SQL section, no tool instructions.
const baseBrief = buildBrahmaSystemPrompt({
  profile: {},
  includeSqlAccess: false,
  toolInstructions: undefined,
});

// Pick a raw-string hash fence that does not collide with the body's `"#`/`#"`.
function fence(body) {
  let hashes = '#';
  while (body.includes(`"${hashes}`) || body.includes(`${hashes}"`)) hashes += '#';
  return hashes;
}
function emit(name, doc, body) {
  const h = fence(body);
  return `/// ${doc}\npub const ${name}: &str = r${h}"${body}"${h};\n`;
}

const out = `//! Generated byte-exact Brahma Console system-prompt surface (W4.5b; v4
//! \`lib/brahma-console/system-prompt-builder.ts\` + \`brahma-sql-prompt.ts\`).
//!
//! Extracted mechanically from the v4 source; do not hand-edit. Regenerate with
//! \`harness/oracle/cases/gen-brahma-prompts.mjs\` if the source changes.

${emit('BRAHMA_BASE_BRIEF', `v4 base brief (${baseBrief.length} UTF-16 code units, no trailing newline).`, baseBrief)}
${emit('BRAHMA_SQL_PROMPT', `v4 \`BRAHMA_SQL_PROMPT\` (${BRAHMA_SQL_PROMPT.length} UTF-16 code units, no trailing newline).`, BRAHMA_SQL_PROMPT)}`;

fs.mkdirSync(OUT.slice(0, OUT.lastIndexOf('/')), { recursive: true });
fs.writeFileSync(OUT, out);
console.error(`wrote ${OUT}: base=${baseBrief.length} sql=${BRAHMA_SQL_PROMPT.length}`);
