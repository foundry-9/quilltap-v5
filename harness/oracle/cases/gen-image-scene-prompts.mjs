/**
 * Mechanical extractor for the image-scene cheap-LLM task prompts (W4.9a).
 * Reads the in-scope system-prompt template literals from v4
 * `lib/memory/cheap-llm-tasks/image-scene-tasks.ts` and emits the byte-exact
 * `services/image_scene_tasks/prompt_text.rs` submodule (the generated
 * `prompt_text` precedent: `memory_tasks/prompt_text.rs`, the danger gatekeeper).
 *
 * [decd8ef9] The story-background prompt is no longer ONE constant: v4 split it
 * into a shared head/tail plus one of two intimacy blocks and one of two worked
 * examples, assembled per call by `buildStoryBackgroundPrompt(uncensoredImage-
 * Target)`. All seven pieces are emitted here; the Rust twin
 * `image_scene_tasks::build_story_background_prompt` performs the identical
 * five-element `'\n\n'` join, so the concealed (default) path stays
 * byte-identical to the pre-split constant.
 *
 * Every template literal is plain (no backtick, no `${...}` interpolation)
 * so they embed verbatim into Rust raw strings. Regenerate whenever the v4
 * source changes:
 *
 *   node ~/source/quilltap-v5/harness/oracle/cases/gen-image-scene-prompts.mjs \
 *     ~/source/quilltap-server \
 *     ~/source/quilltap-v5/crates/quilltap-core/src/services/image_scene_tasks/prompt_text.rs
 */
import * as fs from 'node:fs';

const V4 = process.argv[2];
const OUT = process.argv[3];
if (!V4 || !OUT) {
  console.error('usage: gen-image-scene-prompts.mjs <v4-checkout> <out.rs>');
  process.exit(1);
}

const src = fs.readFileSync(
  `${V4}/lib/memory/cheap-llm-tasks/image-scene-tasks.ts`,
  'utf8',
);

function extract(name) {
  const start = src.indexOf(`const ${name} = \``);
  if (start < 0) throw new Error(`${name} not found`);
  const bodyStart = src.indexOf('`', start) + 1;
  const bodyEnd = src.indexOf('`', bodyStart);
  const body = src.slice(bodyStart, bodyEnd);
  if (body.includes('`') || body.includes('${')) {
    throw new Error(`${name} contains a backtick or interpolation — not raw-embeddable`);
  }
  return body;
}

// Pick a raw-string hash fence that does not collide with the body.
function fence(body) {
  let hashes = '';
  while (body.includes(`"${hashes}`) || body.includes(`${hashes}"`)) hashes += '#';
  // r#"..."# style — the closing is `"` + hashes.
  return hashes.length ? '#'.repeat(hashes.length + 1) : '';
}

function emit(name, doc, body) {
  const h = fence(body);
  const open = h ? `r${h}"` : 'r"';
  const close = h ? `"${h}` : '"';
  return `/// ${doc}\npub const ${name}: &str = ${open}${body}${close};\n`;
}

const craft = extract('IMAGE_PROMPT_CRAFTING_PROMPT');
const appres = extract('APPEARANCE_RESOLUTION_PROMPT');
const appsan = extract('APPEARANCE_SANITIZATION_PROMPT');
const scene = extract('SCENE_CONTEXT_DERIVATION_PROMPT');

// [decd8ef9] The story-background prompt's seven pieces, in `buildStory-
// BackgroundPrompt`'s assembly order (head, intimacy, tail, example, closing).
const storyParts = [
  ['STORY_BACKGROUND_PROMPT_HEAD', 'the shared opening (both variants)'],
  ['STORY_BACKGROUND_CONCEALED_INTIMACY', 'the intimacy block for a MODERATED image provider (the default)'],
  ['STORY_BACKGROUND_CANDID_INTIMACY', 'the intimacy block for a Concierge UNCENSORED image provider'],
  ['STORY_BACKGROUND_PROMPT_TAIL', 'the shared aesthetic guidance + framing examples (both variants)'],
  ['STORY_BACKGROUND_CONCEALED_EXAMPLE', 'the worked intimate-scene example matching the concealed guidance'],
  ['STORY_BACKGROUND_CANDID_EXAMPLE', 'the worked intimate-scene example matching the candid guidance'],
  ['STORY_BACKGROUND_PROMPT_CLOSING', 'the shared closing line (both variants)'],
].map(([name, doc]) => ({ name, doc, body: extract(name) }));

// The builder's own arithmetic, reproduced so the doc comments carry the
// assembled lengths the Rust unit pins assert.
const byName = Object.fromEntries(storyParts.map((p) => [p.name, p.body]));
const assemble = (uncensored) =>
  [
    byName.STORY_BACKGROUND_PROMPT_HEAD,
    uncensored ? byName.STORY_BACKGROUND_CANDID_INTIMACY : byName.STORY_BACKGROUND_CONCEALED_INTIMACY,
    byName.STORY_BACKGROUND_PROMPT_TAIL,
    uncensored ? byName.STORY_BACKGROUND_CANDID_EXAMPLE : byName.STORY_BACKGROUND_CONCEALED_EXAMPLE,
    byName.STORY_BACKGROUND_PROMPT_CLOSING,
  ].join('\n\n');
const concealed = assemble(false);
const candid = assemble(true);

const out = `//! Generated byte-exact model-facing prompt surface for the image-scene
//! cheap-LLM tasks (W4.9a/W4.9c; v4 \`lib/memory/cheap-llm-tasks/image-scene-tasks.ts\`).
//!
//! Extracted mechanically from the v4 source; do not hand-edit. Regenerate with
//! \`harness/oracle/cases/gen-image-scene-prompts.mjs\` if the source changes.

${emit('IMAGE_PROMPT_CRAFTING_PROMPT', `v4 \`IMAGE_PROMPT_CRAFTING_PROMPT\` (${craft.length} UTF-16 code units, no trailing newline).`, craft)}
${emit('APPEARANCE_RESOLUTION_PROMPT', `v4 \`APPEARANCE_RESOLUTION_PROMPT\` (${appres.length} UTF-16 code units, no trailing newline).`, appres)}
${emit('APPEARANCE_SANITIZATION_PROMPT', `v4 \`APPEARANCE_SANITIZATION_PROMPT\` (${appsan.length} UTF-16 code units, no trailing newline).`, appsan)}
${emit('SCENE_CONTEXT_DERIVATION_PROMPT', `v4 \`SCENE_CONTEXT_DERIVATION_PROMPT\` (${scene.length} UTF-16 code units, no trailing newline).`, scene)}
${storyParts
  .map((p) =>
    emit(
      p.name,
      `v4 \`${p.name}\` — ${p.doc} (${p.body.length} UTF-16 code units, no trailing newline).`,
      p.body,
    ),
  )
  .join('\n')}`;

fs.mkdirSync(OUT.slice(0, OUT.lastIndexOf('/')), { recursive: true });
fs.writeFileSync(OUT, out);
console.error(
  `wrote ${OUT}: craft=${craft.length} appres=${appres.length} appsan=${appsan.length} scene=${scene.length} ` +
    storyParts.map((p) => `${p.name}=${p.body.length}`).join(' ') +
    ` | assembled concealed=${concealed.length} candid=${candid.length}`,
);
