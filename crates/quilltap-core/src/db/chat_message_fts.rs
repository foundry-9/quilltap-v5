        assert_eq!(batch.len(), 1, "one batch line: {lines:?}");
        assert!(
            batch[0].starts_with("DEBUG quilltap::db"),
            "level/target: {}",
            batch[0]
        );
        assert!(
            batch[0].contains("context=db.chat-message-fts"),
            "{}",
            batch[0]
        );
