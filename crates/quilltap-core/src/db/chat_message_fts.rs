    /// `EMPTY_AUTHOR_TRUTHINESS_VS_IS_NULL` — the rows of the pairing grid
    /// where v4's SQL fragment and v4's JS predicate disagree, BOTH ways
    /// (L-3): `(systemSender, customAnnouncer)` with `''` in either column —
    /// the SQL excludes (`'' IS NULL` is false), the predicate includes (`''`
    /// is falsy). Every such row is listed; the test fails if a listed row
    /// stops disagreeing or an unlisted one starts.
    const EMPTY_AUTHOR_TRUTHINESS_VS_IS_NULL: &[(Option<&str>, Option<&str>)] =
        &[(Some(""), None), (None, Some("")), (Some(""), Some(""))];

    /// Tier 1 item 2: over a grid of `(type, role, content, systemSender,
    /// customAnnouncer)` rows, the SQL selects exactly what
    /// `is_character_authored_message` accepts — except the named
    /// `EMPTY_AUTHOR_TRUTHINESS_VS_IS_NULL` rows, and except NULL `content`
    /// (`CONTENT_IS_NOT_NULL_HAS_NO_PREDICATE_TWIN`: v4's JS reads
    /// `msg.content.toLowerCase()` on a non-null string, so the predicate has
    /// no content arm and the SQL's `IS NOT NULL` is carved by name).
    #[test]
    fn the_sql_and_the_predicate_agree() {
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch(REDUCED_DDL).unwrap();
        let types = ["message", "system", "context-summary"];
        let roles = [
            Some("USER"),
            Some("ASSISTANT"),
            Some("SYSTEM"),
            Some("TOOL"),
            None,
        ];
        let contents = [Some("words"), None];
        let senders = [None, Some(""), Some("host")];
        let announcers = [
            None,
            Some(""),
            Some(r#"{"kind":"custom","displayName":"Town Crier"}"#),
        ];
        let mut n = 0;
        let mut rows = Vec::new();
        for t in types {
            for r in roles {
                for c in contents {
                    for ss in senders {
                        for ca in announcers {
                            let id = format!("m{n}");
                            n += 1;
                            conn.execute(
                                r#"INSERT INTO "chat_messages" ("id","chatId","type","role","content","systemSender","customAnnouncer","createdAt") VALUES (?,?,?,?,?,?,?,?)"#,
                                rusqlite::params![id, "c", t, r, c, ss, ca, "2026-01-01T00:00:00.000Z"],
                            )
                            .unwrap();
                            rows.push((id, t, r, c, ss, ca));
                        }
                    }
                }
            }
        }
        let sql = format!(
            "SELECT id FROM \"chat_messages\" WHERE {}",
            chat_message_fts_eligibility_sql("")
        );
        let selected: std::collections::HashSet<String> = conn
            .prepare(&sql)
            .unwrap()
            .query_map([], |r| r.get(0))
            .unwrap()
            .collect::<Result<_, _>>()
            .unwrap();
        let mut disagreements = Vec::new();
        for (id, t, r, c, ss, ca) in &rows {
            let mut ev = serde_json::Map::new();
            ev.insert("type".into(), (*t).into());
            if let Some(r) = r {
                ev.insert("role".into(), (*r).into());
            }
            if let Some(ss) = ss {
                ev.insert("systemSender".into(), (*ss).into());
            }
            if let Some(ca) = ca {
                ev.insert("customAnnouncer".into(), (*ca).into());
            }
            let predicate =
                crate::chat_activity::is_character_authored_message(&serde_json::Value::Object(ev));
            let sql_says = selected.contains(id);
            if c.is_none() {
                // CONTENT_IS_NOT_NULL_HAS_NO_PREDICATE_TWIN: the SQL never
                // selects a NULL-content row.
                assert!(!sql_says, "{id}: NULL content selected");
                continue;
            }
            if predicate != sql_says {
                assert!(
                    predicate && !sql_says,
                    "{id}: only the predicate-includes / SQL-excludes direction is named"
                );
                disagreements.push((*ss, *ca, *t, *r));
            }
        }
        // Every disagreement is a named row, on an otherwise-eligible
        // (message, USER|ASSISTANT) shape …
        for (ss, ca, t, r) in &disagreements {
            assert_eq!(*t, "message");
            assert!(matches!(r, Some("USER") | Some("ASSISTANT")));
            assert!(
                EMPTY_AUTHOR_TRUTHINESS_VS_IS_NULL.contains(&(*ss, *ca)),
                "unlisted disagreement: {ss:?} / {ca:?}"
            );
        }
        // … and every named row still disagrees (both roles).
        for named in EMPTY_AUTHOR_TRUTHINESS_VS_IS_NULL {
            assert_eq!(
                disagreements
                    .iter()
                    .filter(|(ss, ca, _, _)| (*ss, *ca) == *named)
                    .count(),
                2,
                "named row {named:?} stopped disagreeing"
            );
        }
        assert_eq!(
            disagreements.len(),
            2 * EMPTY_AUTHOR_TRUTHINESS_VS_IS_NULL.len()
        );
    }

